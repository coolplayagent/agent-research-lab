//! Canonical wire states shared by the IM core, scenario adapters and clients.
//! Preserve serialized values: existing journals and API clients depend on them.
use serde::{Deserialize, Serialize};

macro_rules! states {
    ($($(#[$enum_meta:meta])* $name:ident { $($(#[$variant_meta:meta])* $variant:ident => $wire:literal),+ $(,)? })+) => {
        $(
            #[derive(Clone, Copy, Debug, PartialEq, Eq, PartialOrd, Ord, Serialize, Deserialize)]
            $(#[$enum_meta])*
            pub enum $name { $($(#[$variant_meta])* #[serde(rename = $wire)] $variant),+ }
            impl $name {
                pub const ALL: &'static [Self] = &[$(Self::$variant),+];
                pub const fn as_str(self) -> &'static str {
                    match self { $(Self::$variant => $wire),+ }
                }
                pub const fn code(self) -> &'static str { self.as_str() }
                pub fn parse(value: &str) -> serde_json::Result<Self> {
                    serde_json::from_value(serde_json::Value::String(value.into()))
                }
                /// Unknown external states remain unknown; they never imply success.
                pub fn from_value(value: &serde_json::Value) -> Option<Self> {
                    value.as_str().and_then(|s| Self::parse(s).ok())
                }
            }
            impl std::fmt::Display for $name {
                fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
                    f.write_str(self.as_str())
                }
            }
        )+
        /// Generate executable constants and their associated TypeScript union types.
        pub fn typescript() -> String {
            let mut out = String::from("// Generated by //crates/contracts:generate. Do not edit.\n");
            $(
                out.push_str(concat!("export const ", stringify!($name), " = {\n"));
                $(out.push_str(concat!("  ", stringify!($variant), ": \"", $wire, "\",\n"));)+
                out.push_str(concat!("} as const;\nexport type ", stringify!($name), " = (typeof ", stringify!($name), ")[keyof typeof ", stringify!($name), "];\n"));
            )+
            out
        }
        pub fn catalog() -> serde_json::Value {
            let mut values = serde_json::Map::new();
            $(values.insert(stringify!($name).into(), serde_json::json!($name::ALL));)+
            serde_json::Value::Object(values)
        }
    }
}

